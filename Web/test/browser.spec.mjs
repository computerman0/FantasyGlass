import {test,expect} from '@playwright/test';
test('dashboard, multi-league player details, local scoring, and mobile navigation',async({page})=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.setViewportSize({width:1440,height:1100});await page.goto('http://127.0.0.1:5173/');
 await expect(page.getByRole('heading',{name:'Game day, all together.'})).toBeVisible();
 await page.getByRole('button',{name:'Explore sample dashboard'}).click();
 await expect(page.getByText('Sample mode · These scores are illustrative, not live ESPN data.')).toBeVisible();
 await expect(page.getByText('Sunday Standard',{exact:true})).toBeVisible();
 await page.screenshot({path:'test-results/dashboard-desktop.png',fullPage:true});
 await page.getByRole('button',{name:'Josh Allen QB',exact:false}).first().click();
 await expect(page.getByRole('heading',{name:'Every point, explained'})).toBeVisible();
 await expect(page.getByText('247 × 0.04',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Close',exact:true}).click();
 await page.locator('.sidebar').getByRole('button',{name:'Players'}).click();
 await page.getByPlaceholder('Find a player…').fill('Josh');
 await page.getByRole('button',{name:'Compare league scores'}).click();
 await expect(page.locator('.league-breakout').getByText('Sunday Standard')).toBeVisible();
 await page.locator('.sidebar').getByRole('button',{name:'Leagues'}).click();
 await page.getByRole('button',{name:'Scoring rules'}).first().click();
 await page.getByLabel('Points',{exact:true}).first().fill('0.05');
 await page.getByRole('button',{name:'Save local scoring'}).click();
 await expect(page.getByText('Scoring updated in FantasyGlass. ESPN settings are unchanged.')).toBeVisible();
 await page.setViewportSize({width:390,height:844});
 await page.locator('.mobile-nav').getByRole('button',{name:'Dashboard',exact:true}).click();
 await expect(page.locator('.matchup-card').first()).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:'test-results/dashboard-mobile.png',fullPage:true});
 await page.locator('.mobile-nav').getByRole('button',{name:'Settings',exact:true}).click();
 await page.locator('.setting-row select').first().selectOption('light');
 await expect(page.locator('html')).toHaveAttribute('data-theme','light');
 expect(errors).toEqual([]);
});
test('connect form reports invalid and upstream connection errors without losing input',async({page})=>{
 await page.goto('http://127.0.0.1:5173/');
 await page.getByRole('button',{name:'Connect your first league'}).click();
 await page.getByLabel('League ID or ESPN league link').fill('invalid');
 await page.getByRole('button',{name:'Test connection',exact:true}).click();
 await expect(page.getByRole('alert')).toContainText('valid league ID');
 await expect(page.getByLabel('League ID or ESPN league link')).toHaveValue('invalid');
 await page.getByLabel('This is a private league').check();
 await expect(page.getByText('Your cookies act like a login session.',{exact:false})).toBeVisible();
 await expect(page.getByLabel('espn_s2',{exact:true})).toHaveAttribute('type','password');
});
